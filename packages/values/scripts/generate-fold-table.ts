/**
 * Generates `src/fold-table.ts` from the Unicode Character Database.
 *
 * Run with `pnpm --filter @std/values generate:fold`. It downloads
 * `CaseFolding.txt` (statuses C and F: full case folding) and `DerivedAge.txt`
 * (every assigned code point) for {@link UNICODE_VERSION} and writes a compact,
 * deterministic module. Run `pnpm fix` afterwards; the output is already in
 * the formatter's shape, so formatting leaves it unchanged.
 */
import { writeFileSync } from "node:fs";

const UNICODE_VERSION = "16.0.0";
const BASE_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd`;
const OUTPUT = new URL("../src/fold-table.ts", import.meta.url);
const ENTRIES_PER_LINE = 12;
const HEX = 16;

const DATA_LINE =
  /^(?<from>[0-9A-F]+); (?<status>[CFST]); (?<to>[0-9A-F ]+); #/u;

const AGE_LINE = /^(?<start>[0-9A-F]+)(?:\.\.(?<end>[0-9A-F]+))?\s*;/u;

const download = async (file: string): Promise<string> => {
  const response = await fetch(`${BASE_URL}/${file}`);

  if (!response.ok) {
    throw new Error(`Download of ${file} failed with ${response.status}`);
  }

  const text = await response.text();

  if (!text.includes(`${file.replace(".txt", "")}-${UNICODE_VERSION}.txt`)) {
    throw new Error(`${file} is not the ${UNICODE_VERSION} version`);
  }

  return text;
};

interface Mapping {
  readonly from: number;
  readonly to: readonly number[];
}

const parseFolding = (text: string): Mapping[] => {
  const mappings: Mapping[] = [];

  for (const line of text.split("\n")) {
    const {
      from = "",
      status = "",
      to = "",
    } = DATA_LINE.exec(line)?.groups ?? {};

    if (status === "C" || status === "F") {
      mappings.push({
        from: Number.parseInt(from, HEX),
        to: to
          .trim()
          .split(" ")
          .map((part) => Number.parseInt(part, HEX)),
      });
    }
  }

  return mappings.toSorted((a, b) => a.from - b.from);
};

/** Runs of single-code-point mappings sharing one step and one delta. */
interface Run {
  readonly start: number;
  count: number;
  readonly step: number;
  readonly delta: number;
}

const toRuns = (mappings: readonly Mapping[]): Run[] => {
  const runs: Run[] = [];

  for (const { from, to } of mappings) {
    const [target = 0] = to;
    const delta = target - from;
    const last = runs.at(-1);
    const sameDelta = last !== undefined && last.delta === delta;

    const extendsRun =
      sameDelta && from === last.start + last.count * last.step;

    const startsStride =
      sameDelta && last.count === 1 && from - last.start <= 2;

    if (extendsRun) {
      last.count += 1;
    } else if (startsStride) {
      runs.pop();
      runs.push({
        count: 2,
        delta,
        start: last.start,
        step: from - last.start,
      });
    } else {
      runs.push({ count: 1, delta, start: from, step: 1 });
    }
  }

  return runs;
};

const CODE_POINTS = 0x11_00_00;
const NONCHARACTER_BLOCK_FIRST = 0xfd_d0;
const NONCHARACTER_BLOCK_LAST = 0xfd_ef;
const PLANE_SIZE = 0x1_00_00;

// DerivedAge.txt gives ages to the 66 noncharacters, but their general
// category is Cn (unassigned), as Postgres's unicode_assigned() treats them.
const isNoncharacter = (codePoint: number): boolean =>
  (codePoint >= NONCHARACTER_BLOCK_FIRST &&
    codePoint <= NONCHARACTER_BLOCK_LAST) ||
  codePoint % PLANE_SIZE >= PLANE_SIZE - 2;

const parseAssigned = (text: string): [number, number][] => {
  const assigned = new Uint8Array(CODE_POINTS);

  for (const line of text.split("\n")) {
    const { start, end } = AGE_LINE.exec(line)?.groups ?? {};

    if (start !== undefined) {
      const first = Number.parseInt(start, HEX);
      const last = end === undefined ? first : Number.parseInt(end, HEX);
      assigned.fill(1, first, last + 1);
    }
  }

  const ranges: [number, number][] = [];

  for (const [codePoint, flag] of assigned.entries()) {
    const last = ranges.at(-1);

    if (flag === 1 && !isNoncharacter(codePoint)) {
      if (last !== undefined && last[1] === codePoint - 1) {
        last[1] = codePoint;
      } else {
        ranges.push([codePoint, codePoint]);
      }
    }
  }

  return ranges;
};

const hex = (value: number): string =>
  value < 0 ? `-${(-value).toString(HEX)}` : value.toString(HEX);

const chunkLines = (entries: readonly string[]): string => {
  const lines: string[] = [];

  for (let index = 0; index < entries.length; index += ENTRIES_PER_LINE) {
    lines.push(
      `  "${entries.slice(index, index + ENTRIES_PER_LINE).join(";")}",`
    );
  }

  return lines.join("\n");
};

const render = (
  runs: readonly Run[],
  full: readonly Mapping[],
  assigned: readonly [number, number][]
): string => `// Generated by scripts/generate-fold-table.ts from Unicode ${UNICODE_VERSION}. Do not edit.

/** Unicode version of the fold table. */
export const FOLD_TABLE_UNICODE_VERSION = "${UNICODE_VERSION}";

/**
 * Single-code-point foldings (CaseFolding.txt status C), as
 * \`start,count,step,delta\` runs in hex, separated by \`;\`.
 */
export const SIMPLE_FOLD_RUNS: readonly string[] = [
${chunkLines(runs.map((run) => [run.start, run.count, run.step, run.delta].map(hex).join(",")))}
];

/**
 * Multi-code-point foldings (CaseFolding.txt status F), as
 * \`from:to to...\` in hex, separated by \`;\`.
 */
export const FULL_FOLDINGS: readonly string[] = [
${chunkLines(full.map((mapping) => `${hex(mapping.from)}:${mapping.to.map(hex).join(" ")}`))}
];

/**
 * Assigned code points (DerivedAge.txt without the noncharacters), as
 * \`start-end\` ranges in hex,
 * separated by \`;\`.
 */
export const ASSIGNED_RANGES: readonly string[] = [
${chunkLines(assigned.map(([start, end]) => `${hex(start)}-${hex(end)}`))}
];
`;

const main = async (): Promise<void> => {
  const [folding, ages] = await Promise.all([
    download("CaseFolding.txt"),
    download("DerivedAge.txt"),
  ]);

  const mappings = parseFolding(folding);
  const simple = mappings.filter((mapping) => mapping.to.length === 1);
  const full = mappings.filter((mapping) => mapping.to.length > 1);
  writeFileSync(OUTPUT, render(toRuns(simple), full, parseAssigned(ages)));
};

await main();
